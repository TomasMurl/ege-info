# 2. страшная махинация с суммой цифр двоички
# 3. вернули получившееся число в 10-чку

for N in range(1, 1000):
    N2 = bin(N)[2:] # str
    s = N2.count("1") # int
    if s % 2 == 0:
        N2 = "10" + N2[2:] + "0"
    else:
        N2 = "11" + N2[2:] + "1"
    R = int(N2, 2)
    if R < 35:
        print(N, R)