# n - мощность алфавита
# N - кол-во символов
# i - вес символа
# n = 20
# i = 5 бит = 0,675 -> 1Б
# N = 10
# V = N * i = 10 * 5 = 50 бит = 6,25 Б -> 7 Б

from math import *

# ceil(x) - округляет x в большую сторону
# log2(x) - вычисляет логарифм по основанию 2 от x

n = 1510
N = 105
i = ceil(log2(n))
V = ceil(N * i / 8)
print(16384 * V / 1024)